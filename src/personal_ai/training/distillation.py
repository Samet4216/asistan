@dataclass
class DistillationConfig:
    """Hyperparameters and configuration for knowledge distillation."""
    temperature: float = 2.0
    alpha: float = 0.5  # Weight for hard cross-entropy loss (1-alpha for soft KL loss)
    learning_rate: float = 5e-4
    batch_size: int = 1
    max_seq_len: int = 256
    weight_decay: float = 0.01
    gradient_accumulation_steps: int = 1
    max_vram_mb: float = 5000.0  # 6GB VRAM safety threshold
    device: str = "cuda" if torch.cuda.is_available() else "cpu"

    def __post_init__(self) -> None:
        if self.temperature <= 0:
            raise ValueError(f"Distillation temperature must be > 0, got {self.temperature}")
        if not (0.0 <= self.alpha <= 1.0):
            raise ValueError(f"Alpha must be within [0.0, 1.0], got {self.alpha}")


class DistillationLoss(nn.Module):
    """
    Hinton-style Knowledge Distillation Loss.

    L_total = alpha * L_CE(student, labels) + (1 - alpha) * T^2 * KL(p_S^T || p_T^T)

    Scaling the soft KL loss by T^2 maintains gradient magnitude equilibrium
    with the hard CrossEntropyLoss as temperature varies.
    """

    def __init__(self, temperature: float = 2.0, alpha: float = 0.5, ignore_index: int = -100) -> None:
        super().__init__()
        if temperature <= 0:
            raise ValueError(f"Temperature must be positive, got {temperature}")
        if not (0.0 <= alpha <= 1.0):
            raise ValueError(f"Alpha must be in [0.0, 1.0], got {alpha}")

        self.temperature = temperature
        self.alpha = alpha
        self.ignore_index = ignore_index
        self.ce_loss = nn.CrossEntropyLoss(ignore_index=ignore_index)
        self.kl_loss = nn.KLDivLoss(reduction="batchmean", log_target=False)

    def forward(
        self,
        student_logits: torch.Tensor,
        teacher_logits: torch.Tensor,
        labels: Optional[torch.Tensor] = None,
    ) -> Tuple[torch.Tensor, Dict[str, float]]:
        """
        Compute total distillation loss.

        Args:
            student_logits: Tensor of shape (batch, seq_len, vocab_size) or (batch, vocab_size)
            teacher_logits: Tensor of same shape as student_logits
            labels: Optional ground-truth token IDs for hard cross-entropy

        Returns:
            total_loss: Scalar torch.Tensor
            metrics: Dict with components ('ce_loss', 'kd_loss', 'total_loss')
        """
        # Align shapes if needed (flatten batch and sequence dimensions for CrossEntropy)
        vocab_size = student_logits.size(-1)
        flat_student = student_logits.view(-1, vocab_size)
        flat_teacher = teacher_logits.view(-1, vocab_size)

        # 1. Soft Target Distillation Loss (KL Divergence with Temperature Scaling)
        # Student probabilities: log-softmax at temperature T
        student_log_prob = F.log_softmax(flat_student / self.temperature, dim=-1)
        # Teacher probabilities: softmax at temperature T (detached, no grad through teacher)
        teacher_prob = F.softmax(flat_teacher.detach() / self.temperature, dim=-1)

        kd_loss = self.kl_loss(student_log_prob, teacher_prob) * (self.temperature ** 2)

        # 2. Hard Target Cross-Entropy Loss
        if labels is not None and self.alpha > 0.0:
            flat_labels = labels.view(-1)
            ce_loss = self.ce_loss(flat_student, flat_labels)
            total_loss = self.alpha * ce_loss + (1.0 - self.alpha) * kd_loss
            ce_val = ce_loss.item()
        else:
            total_loss = kd_loss
            ce_val = 0.0

        metrics = {
            "total_loss": total_loss.item(),
            "kd_loss": kd_loss.item(),
            "ce_loss": ce_val,
        }
        return total_loss, metrics


@dataclass
class TeacherSample:
    """Structured sample generated by a teacher model."""
    prompt: str
    output: str
    task_type: str  # 'code', 'math', 'general'
    teacher_model: str
    license: str
    metadata: Dict[str, Any] = field(default_factory=dict)


class TeacherVerificationFilter:
    """
    Automated quality gate for teacher model outputs.

    Validates license compliance, syntax correctness, mathematical validity,
    and checks for degenerate repetition loops.
    """

    ALLOWED_LICENSES = {"apache-2.0", "mit", "llama3.1", "bsd-3-clause"}

    def __init__(self) -> None:
        self.code_validator = CodeValidator()
        self.math_engine = SymbolicMathEngine()

    def verify_license(self, license_str: str) -> bool:
        """Verify license permits derivative distillation / fine-tuning."""
        return license_str.strip().lower() in self.ALLOWED_LICENSES

    def check_repetition_degradation(self, text: str, n_gram_size: int = 4, threshold: float = 0.4) -> bool:
        """
        Detect degenerate token repetition loops.
        Returns True if text is degenerate (repeating), False if clean.
        """
        words = text.split()
        if len(words) < n_gram_size * 3:
            return False

        ngrams = [tuple(words[i : i + n_gram_size]) for i in range(len(words) - n_gram_size + 1)]
        if not ngrams:
            return False

        unique_ratio = len(set(ngrams)) / len(ngrams)
        # If less than threshold of ngrams are unique, it is severely repeating
        return unique_ratio < threshold

    def verify_sample(self, sample: TeacherSample) -> Tuple[bool, str]:
        """
        Full verification pipeline for a teacher sample.

        Returns:
            (is_valid, reason)
        """
        # 1. License Verification
        if not self.verify_license(sample.license):
            return False, f"License '{sample.license}' is not approved for training data generation."

        # 2. Length Check
        text = sample.output.strip()
        if len(text) < 10:
            return False, "Teacher output too short (< 10 chars)."
        if len(text) > 8000:
            return False, "Teacher output exceeds maximum allowable character limit."

        # 3. Degenerate Repetition Check
        if self.check_repetition_degradation(text):
            return False, "Teacher output contains degenerate repetition loops."

        # 4. Domain Specific Quality Checks
        if sample.task_type == "code":
            # Extract code blocks if fenced
            code_to_check = text
            if "```python" in text:
                parts = text.split("```python")
                code_to_check = parts[1].split("```")[0].strip()
            elif "```cpp" in text or "```c++" in text:
                delimiter = "```cpp" if "```cpp" in text else "```c++"
                code_to_check = text.split(delimiter)[1].split("```")[0].strip()
                res = self.code_validator.validate_cpp(code_to_check)
                if not res.valid:
                    return False, f"C++ syntax error in teacher code: {res.error_message}"
                return True, "Verified C++ code."

            # Python syntax validation
            res = self.code_validator.validate_python(code_to_check)
            if not res.valid:
                return False, f"Python syntax error in teacher code: {res.error_message}"

        elif sample.task_type == "math":
            # Basic sanity check on mathematical expressions
            if "= " in text and "\n" not in text:
                expr_parts = text.split("=")
                if len(expr_parts) == 2:
                    lhs, rhs = expr_parts[0].strip(), expr_parts[1].strip()
                    # Check if SymPy can verify or parse equality
                    try:
                        res = self.math_engine.solve_linear_system(f"{lhs} - ({rhs})", "x")
                        # Parsed successfully without crashing
                    except Exception:
                        pass  # Non-fatal if complex math prose

        return True, "Passed all quality verification filters."


class DistillationDataset(Dataset):
    """
    In-memory dataset holding tokenized inputs, teacher soft logits, and target labels.
    """

    def __init__(
        self,
        input_ids: List[torch.Tensor],
        teacher_logits: List[torch.Tensor],
        labels: Optional[List[torch.Tensor]] = None,
    ) -> None:
        self.input_ids = input_ids
        self.teacher_logits = teacher_logits
        self.labels = labels if labels is not None else input_ids

        if len(self.input_ids) != len(self.teacher_logits):
            raise ValueError("Mismatched counts between input_ids and teacher_logits.")

    def __len__(self) -> int:
        return len(self.input_ids)

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        item = {
            "input_ids": self.input_ids[idx],
            "teacher_logits": self.teacher_logits[idx],
            "labels": self.labels[idx],
        }
        return item


class DistillationTrainer:
    """
    Distillation execution engine.

    Trains a compact student model using teacher supervision under
    strict 6GB VRAM budget verification.
    """

    def __init__(
        self,
        student_model: nn.Module,
        teacher_model: Optional[nn.Module] = None,
        config: Optional[DistillationConfig] = None,
    ) -> None:
        self.config = config or DistillationConfig()
        self.student = student_model.to(self.config.device)
        self.teacher = teacher_model.to(self.config.device) if teacher_model is not None else None
        if self.teacher is not None:
            self.teacher.eval()  # Freeze teacher

        self.loss_fn = DistillationLoss(
            temperature=self.config.temperature,
            alpha=self.config.alpha,
        )
        self.optimizer = torch.optim.AdamW(
            self.student.parameters(),
            lr=self.config.learning_rate,
            weight_decay=self.config.weight_decay,
        )

    def _check_vram(self) -> float:
        """Returns allocated VRAM in MB; raises error if budget exceeded."""
        if torch.cuda.is_available() and self.config.device == "cuda":
            allocated_mb = torch.cuda.memory_allocated() / (1024 ** 2)
            if allocated_mb > self.config.max_vram_mb:
                raise RuntimeError(
                    f"VRAM budget exceeded during distillation! Allocated: {allocated_mb:.2f} MB, Limit: {self.config.max_vram_mb} MB"
                )
            return allocated_mb
        return 0.0

    def train_step(
        self,
        input_ids: torch.Tensor,
        cached_teacher_logits: Optional[torch.Tensor] = None,
        labels: Optional[torch.Tensor] = None,
    ) -> Dict[str, float]:
        """
        Execute a single forward-backward optimization step.
        """
        self.student.train()
        self.optimizer.zero_grad()

        input_ids = input_ids.to(self.config.device)
        if labels is not None:
            labels = labels.to(self.config.device)

        start_time = time.perf_counter()

        # Compute teacher logits if not provided precomputed
        if cached_teacher_logits is not None:
            teacher_logits = cached_teacher_logits.to(self.config.device)
        elif self.teacher is not None:
            with torch.no_grad():
                teacher_out = self.teacher(input_ids)
                teacher_logits = teacher_out.logits if hasattr(teacher_out, "logits") else teacher_out
        else:
            raise ValueError("Neither cached_teacher_logits nor teacher_model was provided.")

        # Student forward
        student_out = self.student(input_ids)
        student_logits = student_out.logits if hasattr(student_out, "logits") else student_out

        # Compute loss
        loss, metrics = self.loss_fn(student_logits, teacher_logits, labels)
        loss.backward()

        torch.nn.utils.clip_grad_norm_(self.student.parameters(), max_norm=1.0)
        self.optimizer.step()

        elapsed = time.perf_counter() - start_time
        num_tokens = input_ids.numel()
        tokens_per_sec = num_tokens / elapsed if elapsed > 0 else 0.0

        vram_mb = self._check_vram()

        metrics["tokens_per_sec"] = tokens_per_sec
        metrics["vram_mb"] = vram_mb
        return metrics
