"""Code Syntax & Architecture Verification Tools (Phase 6).

Provides deterministic Python AST parsing, syntax validation, and C++ structure checks.
"""

import ast
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional


@dataclass
class CodeValidationResult:
    """Represents verification status of generated code."""
    valid: bool
    language: str
    error_message: Optional[str] = None
    line_number: Optional[int] = None
    functions_defined: List[str] = field(default_factory=list)
    classes_defined: List[str] = field(default_factory=list)
    imports_found: List[str] = field(default_factory=list)


class CodeValidator:
    """Static analysis and syntax validator for code generated by specialist agents."""

    @staticmethod
    def validate_python(code: str) -> CodeValidationResult:
        """Parses Python source code into an AST and extracts architectural elements."""
        try:
            tree = ast.parse(code)
            functions = [node.name for node in ast.walk(tree) if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))]
            classes = [node.name for node in ast.walk(tree) if isinstance(node, ast.ClassDef)]

            imports = []
            for node in ast.walk(tree):
                if isinstance(node, ast.Import):
                    for alias in node.names:
                        imports.append(alias.name)
                elif isinstance(node, ast.ImportFrom):
                    module = node.module or ""
                    for alias in node.names:
                        imports.append(f"{module}.{alias.name}")

            return CodeValidationResult(
                valid=True,
                language="python",
                functions_defined=functions,
                classes_defined=classes,
                imports_found=imports,
            )
        except SyntaxError as e:
            return CodeValidationResult(
                valid=False,
                language="python",
                error_message=f"SyntaxError: {e.msg}",
                line_number=e.lineno,
            )
        except Exception as ex:
            return CodeValidationResult(
                valid=False,
                language="python",
                error_message=str(ex),
            )

    @staticmethod
    def validate_cpp(code: str) -> CodeValidationResult:
        """Basic balanced-delimiter and syntax check for C++ source snippets."""
        stack = []
        brackets = {")": "(", "}": "{", "]": "["}
        lines = code.splitlines()

        for line_idx, line in enumerate(lines, start=1):
            stripped = line.strip()
            # Ignore comments
            if stripped.startswith("//") or stripped.startswith("/*"):
                continue

            for char in line:
                if char in "({[":
                    stack.append((char, line_idx))
                elif char in ")}]":
                    if not stack:
                        return CodeValidationResult(
                            valid=False,
                            language="cpp",
                            error_message=f"Unmatched closing '{char}'",
                            line_number=line_idx,
                        )
                    last_open, open_line = stack.pop()
                    if brackets[char] != last_open:
                        return CodeValidationResult(
                            valid=False,
                            language="cpp",
                            error_message=f"Mismatched delimiter: expected '{last_open}' to match line {open_line}, but got '{char}'",
                            line_number=line_idx,
                        )

        if stack:
            unclosed, open_line = stack.pop()
            return CodeValidationResult(
                valid=False,
                language="cpp",
                error_message=f"Unclosed opening delimiter '{unclosed}' from line {open_line}",
                line_number=open_line,
            )

        return CodeValidationResult(
            valid=True,
            language="cpp",
        )
